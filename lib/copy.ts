// Helper function to get copy based on current language
export function getCopy(path: string, language: 'el' | 'en' = 'el') {
    const keys = path.split('.')
    let value: any = copy

    for (const key of keys) {
        value = value?.[key]
    }

    if (typeof value === 'object' && value !== null && (language in value)) {
        return value[language]
    }

    return value
}
