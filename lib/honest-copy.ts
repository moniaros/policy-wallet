// Helper function
export function getHonestCopy(path: string, language: 'el' | 'en' = 'el') {
    const keys = path.split('.')
    let value: any = honestCopy

    for (const key of keys) {
        value = value?.[key]
    }

    if (typeof value === 'object' && value !== null && (language in value)) {
        return value[language]
    }

    return value
}
